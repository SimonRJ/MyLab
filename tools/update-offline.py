"""Run from a checkout before publishing changes to the atlas or its assets."""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
scripts = ["explorer.js", "records.js", "globes.js", "vessels.js", "offline-client.js"]
documents = ["index.html", "reader.html", "offline.html", "children-of-time/index.html"]
paths = [root / p for p in documents + scripts + ["atlas.css", "offline.css", "app.webmanifest"]]
for directory in ("media", "icons"):
    paths.extend(path for path in (root / directory).rglob("*") if path.is_file())

def digest(content):
    return hashlib.sha256(content).hexdigest()

files = [[path.relative_to(root).as_posix(), digest(path.read_bytes())] for path in sorted(paths)]
body = json.dumps(files, ensure_ascii=False, separators=(",", ":"))
release = digest(body.encode() + (root / "sw.js").read_bytes())[:20]
(root / "offline-files.js").write_text(
    f'/* Generated by tools/update-offline.py */\nself.ATLAS_PACK={{version:"{release}",files:{body}}};\n',
    encoding="utf-8",
)
print(f"{len(files)} offline files, release {release}")
